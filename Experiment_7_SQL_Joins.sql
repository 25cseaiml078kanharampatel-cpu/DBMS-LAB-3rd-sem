CREATE DATABASE IF NOT EXISTS Exp7DB;
USE Exp7DB;

CREATE TABLE DEPT (
    DeptNo INT PRIMARY KEY,
    DName VARCHAR(50),
    Loc VARCHAR(50)
);

CREATE TABLE EMP (
    EmpNo INT PRIMARY KEY,
    EName VARCHAR(50),
    Salary DECIMAL(10,2),
    Mgr INT,
    DeptNo INT
);

CREATE TABLE SALGRADE (
    Grade CHAR(1),
    LowSal DECIMAL(10,2),
    HighSal DECIMAL(10,2)
);

CREATE TABLE AREAS (
    AreaID INT PRIMARY KEY,
    AreaName VARCHAR(50)
);

